#!/bin/bash
# Builds Spectra for Mac: Spectra.app (SwiftUI, Liquid Glass on macOS 26+, own Python inside), Spectra Updater.app,
# and "Install Spectra.app" (the installer, which carries both) packed in build/Spectra-Installer.dmg.
#
# Optional, for self-updating releases:
#   update-public.key           (made once by: python3 tools/updatekey.py gen private.key update-public.key)
#   SPECTRA_UPDATE_KEY_FILE=…   path to the matching private key, plus RELEASE_TAG=v1.0.1  -> also writes build/latest.json
# Needs Xcode (use Xcode 26+ for real glass) and an internet connection the first time (downloads Python).
set -euo pipefail
cd "$(dirname "$0")"

CORE="../fabric_launcher.py"
[ -f "$CORE" ] || { echo "Can't find $CORE (build from inside the repo)"; exit 1; }

CACHE="build/cache"
mkdir -p "$CACHE"

# Apple Silicon only by default (macOS 26+ and Liquid Glass are for Apple Silicon Macs).
# Run with UNIVERSAL=1 ./build.sh to also include Intel.
if [ "${UNIVERSAL:-0}" = "1" ]; then
  SWIFT_ARCHS="--arch arm64 --arch x86_64"
  PY_ARCHS="aarch64:arm64 x86_64:x86_64"
else
  SWIFT_ARCHS="--arch arm64"
  PY_ARCHS="aarch64:arm64"
fi

# --- Python runtime (python-build-standalone, one per CPU type so the app is universal) -------------
fetch_python() {   # $1 = aarch64 | x86_64
  local out="$CACHE/python-$1.tar.gz"
  if [ ! -f "$out" ]; then
    echo "Finding Python for $1…"
    local tag base name
    # Ask the API (with a token when we have one: anonymous calls get rate-limited on CI runners),
    # and fall back to the "latest release" redirect.
    local auth=()
    [ -n "${GH_TOKEN:-}" ] && auth=(-H "Authorization: Bearer $GH_TOKEN")
    tag=$(curl -fsSL "${auth[@]}" https://api.github.com/repos/astral-sh/python-build-standalone/releases/latest \
      | grep -o '"tag_name": *"[^"]*"' | head -1 | sed 's/.*"\([^"]*\)"$/\1/' || true)
    if [ -z "$tag" ]; then
      tag=$(curl -fsSL -o /dev/null -w '%{url_effective}' https://github.com/astral-sh/python-build-standalone/releases/latest | sed 's|.*/tag/||' || true)
    fi
    [ -n "$tag" ] || { echo "Couldn't reach GitHub to find the latest Python release."; exit 1; }
    base="https://github.com/astral-sh/python-build-standalone/releases/download/$tag"
    # the release has hundreds of files, so read its checksum list instead of the (truncated) API asset list
    name=$(curl -fsSL "$base/SHA256SUMS" | grep -o "cpython-3\.12\.[0-9]*+[0-9]*-$1-apple-darwin-install_only_stripped\.tar\.gz" | head -1 || true)
    [ -n "$name" ] || { echo "No Python 3.12 build for $1 in release $tag."; exit 1; }
    echo "Downloading $name"
    curl -fL "$base/$name" -o "$out.part" && mv "$out.part" "$out"
  fi
}
for pair in $PY_ARCHS; do fetch_python "${pair%%:*}"; done

VERSION="$(tr -d '[:space:]' < VERSION)"
echo "Version $VERSION"

# Bake the public update key into the updater (it only installs updates signed by the matching private key).
KEYSWIFT="Sources/SpectraShared/UpdateKey.generated.swift"
if [ -f update-public.key ]; then
  cat > "$KEYSWIFT" <<SWIFT
// Generated by build.sh from update-public.key
public enum UpdateKey {
    public static let publicKey = "$(tr -d '[:space:]' < update-public.key)"
}
SWIFT
else
  echo "NOTE: no update-public.key, so this build's updater can't verify updates (see README)."
fi

echo "Building the apps…"
swift build -c release $SWIFT_ARCHS
BINDIR="$(swift build -c release $SWIFT_ARCHS --show-bin-path)"

ICON_ICNS="build/AppIcon.icns"
iconutil -c icns AppIcon.iconset -o "$ICON_ICNS"

# make_bundle <path.app> <exe name> <display name> <bundle id> <version>
make_bundle() {
  local app="$1" exe="$2" name="$3" bid="$4" ver="$5"
  rm -rf "$app"
  mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
  cp "$BINDIR/$exe" "$app/Contents/MacOS/$exe"
  cp "$ICON_ICNS" "$app/Contents/Resources/AppIcon.icns"
  cat > "$app/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>$name</string>
  <key>CFBundleDisplayName</key><string>$name</string>
  <key>CFBundleIdentifier</key><string>$bid</string>
  <key>CFBundleExecutable</key><string>$exe</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>$ver</string>
  <key>CFBundleVersion</key><string>$ver</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSApplicationCategoryType</key><string>public.app-category.games</string>
</dict></plist>
PLIST
}

# --- Spectra.app ---------------------------------------------------------------------------------
APP="build/Spectra.app"
make_bundle "$APP" Spectra "Spectra" "site.mcpacks.spectra.mac" "$VERSION"
cp "$CORE" "$APP/Contents/Resources/fabric_launcher.py"

for pair in $PY_ARCHS; do
  src="${pair%%:*}"; dst="python-${pair##*:}"
  tmp="$(mktemp -d)"
  tar -xzf "$CACHE/python-$src.tar.gz" -C "$tmp"
  mv "$tmp/python" "$APP/Contents/Resources/$dst"
  rm -rf "$tmp"
  # the launcher is GUI-free in this mode, so the biggest parts of Python can go
  rm -rf "$APP/Contents/Resources/$dst"/lib/python3.12/{test,idlelib,tkinter,turtledemo} \
         "$APP/Contents/Resources/$dst"/lib/tcl* "$APP/Contents/Resources/$dst"/lib/tk* \
         "$APP/Contents/Resources/$dst"/lib/itcl* "$APP/Contents/Resources/$dst"/lib/thread* 2>/dev/null || true
done

# Ad-hoc sign every Mach-O (the bundled Python has many) then the app. Not notarized.
find "$APP/Contents/Resources" -type f \( -name "*.dylib" -o -name "*.so" -o -perm +111 \) -print0 |
  while IFS= read -r -d '' f; do
    if file -b "$f" | grep -q Mach-O; then codesign --force --sign - "$f" >/dev/null 2>&1 || true; fi
  done
codesign --force --deep --sign - "$APP"

# --- Spectra Updater.app -------------------------------------------------------------------------
UPD="build/Spectra Updater.app"
make_bundle "$UPD" SpectraUpdater "Spectra Updater" "site.mcpacks.spectra.updater" "$VERSION"
codesign --force --deep --sign - "$UPD"

# --- zips (what the updater downloads, and what the installer carries) -----------------------------
rm -f build/Spectra-app.zip "build/Spectra-Updater-app.zip"
ditto -c -k --keepParent "$APP" build/Spectra-app.zip
ditto -c -k --keepParent "$UPD" build/Spectra-Updater-app.zip

# --- Install Spectra.app ---------------------------------------------------------------------------
INST="build/Install Spectra.app"
make_bundle "$INST" SpectraInstaller "Install Spectra" "site.mcpacks.spectra.installer" "$VERSION"
cp build/Spectra-app.zip build/Spectra-Updater-app.zip "$INST/Contents/Resources/"
echo "$VERSION" > "$INST/Contents/Resources/payload-version.txt"
codesign --force --deep --sign - "$INST"

echo "Packing Spectra-Installer.dmg…"
rm -f build/Spectra-Installer.dmg
STAGE="$(mktemp -d)"
cp -R "$INST" "$STAGE/"
hdiutil create -quiet -volname "Install Spectra" -srcfolder "$STAGE" -ov -format UDZO build/Spectra-Installer.dmg
rm -rf "$STAGE"

# --- signed update manifest (release builds) -------------------------------------------------------
if [ -n "${SPECTRA_UPDATE_KEY_FILE:-}" ] && [ -n "${RELEASE_TAG:-}" ]; then
  URL="https://github.com/mcpacks-site/Spectra-launcher/releases/download/$RELEASE_TAG/Spectra-app.zip"
  python3 tools/updatekey.py sign "$SPECTRA_UPDATE_KEY_FILE" "$VERSION" build/Spectra-app.zip "$URL" build/latest.json "${RELEASE_NOTES:-}"
fi

echo
echo "Done:"
ls -1 build/Spectra-Installer.dmg build/Spectra-app.zip build/latest.json 2>/dev/null || true
echo "Try it: open build/Spectra-Installer.dmg"
